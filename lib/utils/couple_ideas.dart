/// Frage für einen Tag – bei euch beiden dieselbe (zählt die Tage seit 2026).
String questionFor(DateTime day) {
  final index = DateTime.utc(
    day.year,
    day.month,
    day.day,
  ).difference(DateTime.utc(2026)).inDays;
  return dailyQuestions[index % dailyQuestions.length];
}

String todaysQuestion() => questionFor(today());

